package org.apache.flink.connector.jdbc.core.datastream.sink;

import org.apache.flink.configuration.Configuration;
import org.apache.flink.configuration.PipelineOptions;
import org.apache.flink.connector.jdbc.JdbcConnectionOptions;
import org.apache.flink.connector.jdbc.JdbcExactlyOnceOptions;
import org.apache.flink.connector.jdbc.derby.DerbyTestBase;
import org.apache.flink.runtime.OperatorIDPair;
import org.apache.flink.runtime.jobgraph.JobGraph;
import org.apache.flink.runtime.jobgraph.JobVertex;
import org.apache.flink.streaming.api.datastream.DataStreamSink;
import org.apache.flink.streaming.api.environment.StreamExecutionEnvironment;

import org.junit.jupiter.api.Test;

import javax.annotation.Nullable;

import java.util.stream.Collectors;
import java.util.stream.StreamSupport;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Tests the job graph of the {@link JdbcSink}. The at-least-once sink keeps the job graph of
 * earlier releases; only the exactly-once committer runs in a task of its own.
 */
class JdbcSinkTopologyTest implements DerbyTestBase {

    @Test
    void testExactlyOnceCommitterRunsInItsOwnTask() {
        JobGraph graph = jobGraph(true, null, new Configuration());
        assertThat(vertex(graph, "Writer").getID())
                .isNotEqualTo(vertex(graph, "Committer").getID());
    }

    @Test
    void testAtLeastOnceWriterAndCommitterAreChained() {
        JobGraph graph = jobGraph(false, null, new Configuration());
        assertThat(vertex(graph, "Writer").getID()).isEqualTo(vertex(graph, "Committer").getID());
    }

    /** A savepoint of a sink without a uid finds the writer by its generated operator id. */
    @Test
    void testWriterKeepsItsOperatorIdWithoutUid() {
        assertThat(vertex(jobGraph(true, null, new Configuration()), "Writer").getID())
                .isEqualTo(vertex(jobGraph(false, null, new Configuration()), "Writer").getID());
    }

    @Test
    void testWriterAndCommitterKeepTheirOperatorIdsWithUid() {
        JobGraph exactlyOnce = jobGraph(true, "sink", new Configuration());
        JobGraph atLeastOnce = jobGraph(false, "sink", new Configuration());

        assertThat(vertex(exactlyOnce, "Writer").getID())
                .isEqualTo(vertex(atLeastOnce, "Writer").getID());
        assertThat(
                        vertex(atLeastOnce, "Writer").getOperatorIDs().stream()
                                .map(OperatorIDPair::getGeneratedOperatorID)
                                .collect(Collectors.toList()))
                .contains(
                        vertex(exactlyOnce, "Committer")
                                .getOperatorIDs()
                                .get(0)
                                .getGeneratedOperatorID());
    }

    @Test
    void testExactlyOnceCommitterRunsInItsOwnTaskWithoutAutoGeneratedUids() {
        Configuration config = new Configuration();
        config.set(PipelineOptions.AUTO_GENERATE_UIDS, false);
        JobGraph graph = jobGraph(true, "sink", config);
        assertThat(vertex(graph, "Writer").getID())
                .isNotEqualTo(vertex(graph, "Committer").getID());
    }

    /**
     * The pre-commit map holds no state, so turning auto-generated uids off or on keeps the ids.
     */
    @Test
    void testWriterAndCommitterKeepTheirOperatorIdsWithoutAutoGeneratedUids() {
        Configuration config = new Configuration();
        config.set(PipelineOptions.AUTO_GENERATE_UIDS, false);
        JobGraph withAutoGeneratedUids = jobGraph(true, "sink", new Configuration());
        JobGraph withoutAutoGeneratedUids = jobGraph(true, "sink", config);

        assertThat(vertex(withoutAutoGeneratedUids, "Writer").getID())
                .isEqualTo(vertex(withAutoGeneratedUids, "Writer").getID());
        assertThat(vertex(withoutAutoGeneratedUids, "Committer").getID())
                .isEqualTo(vertex(withAutoGeneratedUids, "Committer").getID());
    }

    /** The rebalance puts the writer at the head of its vertex, which then has the writer's id. */
    private JobGraph jobGraph(boolean exactlyOnce, @Nullable String uid, Configuration config) {
        StreamExecutionEnvironment env = StreamExecutionEnvironment.getExecutionEnvironment(config);
        env.setParallelism(2);
        JdbcSinkBuilder<Long> builder =
                new JdbcSinkBuilder<Long>()
                        .withQueryStatement(
                                "INSERT INTO t VALUES (?)", (ps, id) -> ps.setLong(1, id));
        JdbcSink<Long> sink =
                exactlyOnce
                        ? builder.buildExactlyOnce(
                                JdbcExactlyOnceOptions.defaults(),
                                getMetadata().getXaSourceSupplier())
                        : builder.buildAtLeastOnce(
                                new JdbcConnectionOptions.JdbcConnectionOptionsBuilder()
                                        .withUrl(getMetadata().getJdbcUrl())
                                        .build());
        DataStreamSink<Long> stream =
                env.fromSequence(1, 10).uid("source").rebalance().sinkTo(sink);
        if (uid != null) {
            stream.uid(uid);
        }
        return env.getStreamGraph().getJobGraph();
    }

    private static JobVertex vertex(JobGraph graph, String operator) {
        return StreamSupport.stream(graph.getVertices().spliterator(), false)
                .filter(vertex -> vertex.getName().contains(operator))
                .findFirst()
                .orElseThrow(() -> new AssertionError("No vertex with " + operator));
    }
}
